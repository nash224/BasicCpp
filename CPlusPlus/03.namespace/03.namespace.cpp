//

#include <iostream>
#include "Header1.h"
#include "Header2.h"

namespace MySpace
{

    int Spacefunc()
    {
        return 1;
    }

    void foo()
    {
        // cout 도 std:: 이름 공간에 정의되어 있다.
        std::cout << "MySpace에서" << Spacefunc() << "을 출력했습니다." << std::endl;
    }
}

