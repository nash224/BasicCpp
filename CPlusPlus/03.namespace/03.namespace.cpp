    // 나중에 코드를 짜다보면 내 함수명은 알 수 있을지 몰라도 다른사람이 정의해놓은 함수명과 겹칠 수 있다.
    // 그래서 중복된 함수명을 방지하기 위해 네임 스페이스라는게 있다.
    // namespace는 다른 공간이라고 생가각하면 된다.
